import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import test from 'node:test';
import { query } from '../src/infra/database/query.js';
import { DiscoveryRepository } from '../src/infra/discovery/discovery.repository.js';
import { createCollectionContext } from '../src/bootstrap/collection-context.js';
import type { DiscoveryHttpPort } from '../src/infra/discovery/discovery.http.js';

const expectedUrl = 'postgresql://radar_test:radar_test_local@127.0.0.1:55433/radar_prisma';
if (process.env.DATABASE_URL !== expectedUrl) throw new Error('Postgres discovery integration requires the exact isolated radar_prisma fixture URL.');

test('DiscoveryService uses real repository SQL, precedence/CAS and run ledger with fake-only HTTP', async () => {
  const id = `discovery-migration-${randomUUID()}`;
  const siteDomain = `${id}.example.test`;
  const domainUrl = `tenant-${id}.leilao.br`;
  const externalId = id;
  let runId: number | undefined;
  const repository = new DiscoveryRepository();
  const http: DiscoveryHttpPort = {
    fenajuPage: async () => ({ data: [{ id: externalId, nome: 'Migration fixture', matricula: 'DISC-001', juntaSigla: 'JUCESP', juntaUF: 'sp', situacao: 'Regular', dominio: `declared-${id}.example.test`, dominio_url: `tenant-${id}.leilao.br`, email: `user@fallback-${id}.example.test` }], totalPages: 1 }),
    probe: async () => { throw new Error('external HTTP must not run in postgres integration'); },
  };
  const context = await createCollectionContext({ discovery: true, discoveryDependencies: { repository, http } });
  assert.ok(context.discovery, 'headless collection context provides DiscoveryService');
  try {
    const [{ name }] = await query<{ name: string }>('SELECT current_database() AS name');
    assert.equal(name, 'radar_prisma');

    // Establish a prior site-reconciled domain; the service must preserve it,
    // while retaining the separate domain_url association from legacy behavior.
    const first = await repository.upsertAuctioneer([
      externalId, 'Migration fixture', 'DISC-001', 'JUCESP', 'SP', 'Regular', siteDomain,
      'reconciliado_site_fenaju', null, null, null, null, `tenant-${id}.leilao.br`,
    ]);
    assert.equal(first?.domain, siteDomain);
    const result = await context.discovery!.descobrirFenaju();
    assert.equal(result.leiloeiros, 1);
    assert.equal(result.comLeilaoBr, 1);
    const [auctioneer] = await query<{ domain: string; domain_origin: string }>(
      'SELECT domain, domain_origin FROM auctioneers WHERE registry=$1 AND external_id=$2', ['fenaju', externalId]);
    assert.deepEqual(auctioneer, { domain: siteDomain, domain_origin: 'reconciliado_site_fenaju' });
    const [site] = await query<{ auctioneers: number; ufs: string[] }>('SELECT auctioneers, ufs FROM discovered_sites WHERE domain=$1', [siteDomain]);
    assert.deepEqual(site, { auctioneers: 1, ufs: ['SP'] });
    const rows = await query<{ domain: string }>('SELECT domain FROM discovered_sites WHERE domain = ANY($1::text[])', [[`declared-${id}.example.test`, domainUrl, `fallback-${id}.example.test`]]);
    assert.deepEqual(rows, [{ domain: domainUrl }], 'declared is precedence; domain_url remains separately associated as legacy behavior');

    // Reconciled identity CAS: divergent identity yields no RETURNING row.
    const rejected = await repository.upsertAuctioneer([
      externalId, 'Concurrent edit', 'DISC-001', 'JUCESP', 'SP', 'Regular', 'incoming.example.test',
      'declarado', null, null, null, null, null,
    ]);
    assert.equal(rejected, undefined);

    await query(`UPDATE discovered_sites SET platform='soleon', connector_id=NULL WHERE domain=$1`, [siteDomain]);
    await repository.updateProbe(siteDomain, { status: 200, hasLots: true, platform: 'vip-leiloes', title: 'fixture', note: null }, null);
    const [preserved] = await query<{ platform: string; connector_id: string | null }>(
      'SELECT platform, connector_id FROM discovered_sites WHERE domain=$1', [siteDomain]);
    assert.deepEqual(preserved, { platform: 'soleon', connector_id: null });

    runId = await repository.startRun('fenaju', 'discover');
    await repository.finishRun(runId, { ok: true, fetched: 1, upserted: 1, skipped: 0 });
    const [run] = await query<{ ok: boolean; fetched: number; upserted: number }>(
      'SELECT ok, fetched, upserted FROM collection_runs WHERE id=$1', [runId]);
    assert.deepEqual(run, { ok: true, fetched: 1, upserted: 1 });
  } finally {
    try {
      // Restrict cleanup to identifiers generated by this test only.
      await query('DELETE FROM discovered_sites WHERE domain = ANY($1::text[])', [[siteDomain, domainUrl]]);
      await query('DELETE FROM auctioneers WHERE registry=$1 AND external_id=$2', ['fenaju', externalId]);
      if (runId !== undefined) await query('DELETE FROM collection_runs WHERE id=$1', [runId]);
    } finally {
      await context.close();
    }
  }
});
